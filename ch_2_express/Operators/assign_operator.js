
// below al the assignment operator which use in javascript


// -=
let x = 10
x -= 4;   // x = x - 4
console.log(x); // 6

// +=
let x = 5;
x += 3;   // x = x + 3
console.log(x); // 8

// *=
let x = 4;
x *= 5;   // x = x * 5
console.log(x); // 20

// /=
let x = 20;
x /= 4;   // x = x / 4
console.log(x); // 5

// %=
let x = 10;
x %= 3;   // x = x % 3
console.log(x); // 1

//**=
let x = 2;
x **= 3;   // x = x ** 3
console.log(x); // 8

//string assignment
let text = "Hello";
text += " World";

console.log(text); // Hello World

